/**
 * Определение намерения по свободному тексту на главной кабинета (без сервера и без ИИ-провайдера):
 * страховой случай («меня затопили соседи») или новая потребность («хочу застраховать свадьбу»).
 * Ошибка распознавания не опасна: на обоих экранах можно перейти в другой сценарий.
 */
const INCIDENT = /(затопил|залил|залив|протеч|потоп|пожар|сгорел|возгоран|украл|угнал|угон|кража|ограб|дтп|авари|врезал|столкн|царап|вмятин|разбил|скол|поврежд|сломал|град |упало дерево)/i;
const NEED = /(хочу застрахов|застраховать|нужна страховк|нужен полис|оформить полис|подобрать страх|планирую|собираюсь)/i;

export function looksLikeIncident(text: string): boolean {
  if (NEED.test(text)) return false;
  return INCIDENT.test(text);
}
